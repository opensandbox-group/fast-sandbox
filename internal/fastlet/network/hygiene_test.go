func parseFixture(t *testing.T, mutate func(sections map[string]string)) *netState {
	t.Helper()
	state, err := parseNetState(captureFixture(t, mutate))
	require.NoError(t, err)
	return state
}

func TestParseNetStateCapturesEveryAuditedDomain(t *testing.T) {
	state := parseFixture(t, nil)

	require.Equal(t, []GoldenLink{
		{Name: "eth0", Type: "ether", AdminUp: true, MTU: 1500, MAC: "6a:00:00:00:00:01"},
		{Name: "lo", Type: "loopback", AdminUp: true, MTU: 65536, MAC: "00:00:00:00:00:00"},
		{Name: "vmtap0", Type: "ether", AdminUp: true, MTU: 1500, MAC: "02:00:00:00:00:02"},
	}, state.Links)
	require.Contains(t, state.Addresses, GoldenAddress{Link: "eth0", Family: "inet", Address: "172.30.0.2/24"})
	require.Contains(t, state.Addresses, GoldenAddress{Link: "eth0", Family: "inet6", Address: "fe80::6800:ff:fe00:1/64"})
	require.Contains(t, state.Routes, GoldenRoute{Destination: "default", Gateway: "172.30.0.1", Device: "eth0"})
	require.Equal(t, []GoldenNeighbour{{Destination: "172.30.0.9", Device: "eth0", MAC: "aa:bb:cc:dd:ee:01", Permanent: true}}, state.Neighbours)
	require.Contains(t, state.Qdiscs, GoldenQdisc{Device: "vmtap0", Kind: "clsact", Parent: "ffff:fff1"})
	require.Equal(t, "1", state.Sysctls["net.ipv4.ip_forward"])

	// Firewall counters are pressure- and clock-dependent and are stripped;
	// rule order is preserved.
	require.Contains(t, state.Firewall, ":FORWARD ACCEPT")
	require.Contains(t, state.Firewall, "-A FORWARD -d 172.30.0.1/32 -j ACCEPT")
	require.NotContains(t, strings.Join(state.Firewall, "\n"), "12:3456")
	require.NotContains(t, strings.Join(state.Firewall, "\n"), "Generated by")

	golden := state.golden()
	require.Equal(t, state.Sysctls, golden.Sysctls)
	require.Equal(t, state.Firewall, golden.Firewall)
}

// TestAuditDetectsInjectedResidueClasses mirrors the injection-audit method:
// every residue class is deliberately present in the audited state and the
// audit must name the violated domain. Functional smoke tests catch none of
// the silent classes, so state-level detection is the contract.
func TestAuditDetectsInjectedResidueClasses(t *testing.T) {
	golden := parseFixture(t, nil).golden()

	cases := []struct {
		name   string
		mutate func(state *netState)
		domain string
		detail string
	}{
		{
			name:   "link admin down",
			mutate: func(state *netState) { state.Links[0].AdminUp = false },
			domain: "link", detail: "admin state",
		},
		{
			name:   "tap mac drift",
			mutate: func(state *netState) { state.Links[2].MAC = "aa:bb:cc:dd:ee:02" },
			domain: "link", detail: "address aa:bb:cc:dd:ee:02",
		},
		{
			name: "host side address removed",
			mutate: func(state *netState) {
				state.Addresses = removeAddress(state.Addresses, "eth0|inet|172.30.0.2/24")
			},
			domain: "address", detail: "missing eth0|inet|172.30.0.2/24",
		},
		{
			name: "extra address",
			mutate: func(state *netState) {
				state.Addresses = append(state.Addresses, GoldenAddress{Link: "eth0", Family: "inet", Address: "10.66.6.6/32"})
			},
			domain: "address", detail: "residue eth0|inet|10.66.6.6/32",
		},
		{
			name: "stale blackhole route",
			mutate: func(state *netState) {
				state.Routes = append(state.Routes, GoldenRoute{Type: "blackhole", Destination: "10.88.0.0/16"})
			},
			domain: "route", detail: "10.88.0.0/16",
		},
		{
			name: "stale link route",
			mutate: func(state *netState) {
				state.Routes = append(state.Routes, GoldenRoute{Destination: "10.77.0.0/16", Device: "eth0"})
			},
			domain: "route", detail: "10.77.0.0/16",
		},
		{
			name: "stray permanent neighbour",
			mutate: func(state *netState) {
				state.Neighbours = append(state.Neighbours, GoldenNeighbour{Destination: "172.30.0.77", Device: "eth0", MAC: "aa:bb:cc:dd:ee:03", Permanent: true})
			},
			domain: "neighbour", detail: "172.30.0.77",
		},
		{
			name: "netem qdisc installed",
			mutate: func(state *netState) {
				state.Qdiscs = append(state.Qdiscs, GoldenQdisc{Device: "eth0", Kind: "netem", Root: true})
			},
			domain: "qdisc", detail: "eth0|netem|root",
		},
		{
			name: "tbf qdisc installed",
			mutate: func(state *netState) {
				state.Qdiscs = append(state.Qdiscs, GoldenQdisc{Device: "eth0", Kind: "tbf", Root: true})
			},
			domain: "qdisc", detail: "eth0|tbf|root",
		},
		{
			name: "netns sysctl drift",
			mutate: func(state *netState) {
				state.Sysctls["net.ipv4.ip_forward"] = "0"
			},
			domain: "sysctl", detail: "net.ipv4.ip_forward=0, want 1",
		},
		{
			name: "firewall rule removed",
			mutate: func(state *netState) {
				for index, line := range state.Firewall {
					if line == "-A OUTPUT -d 172.30.0.1/32 -j ACCEPT" {
						state.Firewall = append(state.Firewall[:index], state.Firewall[index+1:]...)
						break
					}
				}
			},
			domain: "firewall", detail: "rule set",
		},
		{
			name:   "leftover listener",
			mutate: func(state *netState) { state.Listeners = []string{"tcp 0.0.0.0:47231"} },
			domain: "socket", detail: "leftover listener tcp 0.0.0.0:47231",
		},
	}

	for _, testCase := range cases {
		t.Run(testCase.name, func(t *testing.T) {
			current := parseFixture(t, nil)
			testCase.mutate(current)
			violations := diffGolden(golden, current)
			require.NotEmpty(t, violations)
			matched := false
			for _, violation := range violations {
				if violation.Domain == testCase.domain && strings.Contains(violation.Detail, testCase.detail) {
					matched = true
				}
			}
			require.Truef(t, matched, "expected %s violation containing %q in %v", testCase.domain, testCase.detail, violations)
		})
	}
}

