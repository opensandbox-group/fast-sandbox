func TestForeignMembersScansProcNetworkNamespaces(t *testing.T) {
	root := t.TempDir()
	procDir := filepath.Join(root, "proc")
	netnsPath := filepath.Join(root, "netns", "fsb-test")
	require.NoError(t, os.MkdirAll(filepath.Dir(netnsPath), 0o755))
	require.NoError(t, os.WriteFile(netnsPath, []byte{}, 0o644))
	require.NoError(t, os.MkdirAll(procDir, 0o755))

	memberDir := filepath.Join(procDir, "4321", "ns")
	require.NoError(t, os.MkdirAll(memberDir, 0o755))
	require.NoError(t, os.Symlink(netnsPath, filepath.Join(memberDir, "net")))
	otherDir := filepath.Join(procDir, "5321", "ns")
	require.NoError(t, os.MkdirAll(otherDir, 0o755))
	other := filepath.Join(root, "other-netns")
	require.NoError(t, os.WriteFile(other, []byte{}, 0o644))
	require.NoError(t, os.Symlink(other, filepath.Join(otherDir, "net")))
	require.NoError(t, os.MkdirAll(filepath.Join(procDir, "1"), 0o755))

	members, err := foreignMembers(procDir, netnsPath)
	require.NoError(t, err)
	require.Equal(t, []int{4321}, members)
}

func TestGuestResetLinesCoverBatchAndLegacyDataPlanes(t *testing.T) {
	driver := NewGuestVMNetNSDriver(LinuxDriverConfig{})

	batch := &Slot{ID: "slot-a", IP: "172.30.0.2", GuestIP: "172.30.0.3", GuestNATBatch: true}
	lines, err := driver.guestResetLines(batch)
	require.NoError(t, err)
	require.Contains(t, strings.Join(lines, "\n"), "iptables -t nat -F "+guestDNATChain)
	require.Contains(t, strings.Join(lines, "\n"), "iptables -t nat -F "+guestSNATChain)
	require.Contains(t, strings.Join(lines, "\n"), "iptables -t nat -C PREROUTING -j "+guestDNATChain)

	legacy := &Slot{ID: "slot-a", IP: "172.30.0.2", GuestIP: "172.30.0.3"}
	lines, err = driver.guestResetLines(legacy)
	require.NoError(t, err)
	require.Len(t, lines, 2)
	require.Contains(t, lines[0], "iptables -t nat -D PREROUTING -d 172.30.0.2/32 -j DNAT --to-destination 172.30.0.3")
	require.Contains(t, lines[1], "iptables -t nat -D POSTROUTING -s 172.30.0.3/32 -j SNAT --to-source 172.30.0.2")

	// Slot identity fields are durable inputs, not kernel output: invalid
	// addresses must be rejected before they reach the reset shell.
	_, err = driver.guestResetLines(&Slot{ID: "slot-a", IP: "172.30.0.2; reboot", GuestIP: "172.30.0.3"})
	require.Error(t, err)
	_, err = driver.guestResetLines(&Slot{ID: "slot-a", IP: "172.30.0.2", GuestIP: "not-an-ip"})
	require.Error(t, err)
}
